#!/usr/bin/env python3
"""Viewpoint ablation statistical tests (WP1 in the paper).

Reads per-VP classification fold_details.csv files regenerated by
`01_run_classification.py` and writes:
    results/viewpoint_comparison/ablation_significance.csv
    results/viewpoint_comparison/rank_correlations_ablation.csv
    results/viewpoint_comparison/variance_comparison.csv

Mirrors the original `scripts/run_ablation_statistics.py`, retargeted to the
to_share `results/` tree and limited to the three corpora in the paper.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import levene, spearmanr, wilcoxon

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))

from folk_patterns_repro.classification import cohens_d, corrected_resampled_ttest

CORPORA = ["symbtr", "the_session", "essen"]
VP_CONFIGS = ["M", "R", "B", "MR", "MB", "RB", "MRB"]
#: The fixed per-corpus classifier the paper reports throughout (Sec. 3.3). Both the global and
#: the combined cell of every comparison use it, so a viewpoint contrast never mixes classifiers.
#: (An earlier version selected the best classifier per cell, which made three Essen rows compare
#: a gbm `global` against a logistic `combined`.)
PAPER_MODEL = {"symbtr": "logistic", "the_session": "rf", "essen": "gbm"}
# k-fold splits per corpus (all three use 10-fold; n_repeats=3). Needed for the
# Nadeau-Bengio correction factor 1/n + n_test/n_train with n_test/n_train = 1/(k-1).
N_SPLITS = {"symbtr": 10, "the_session": 10, "essen": 10}
RESULTS_DIR = REPO_ROOT / "results"
OUT_DIR = RESULTS_DIR / "viewpoint_comparison"
OUT_DIR.mkdir(parents=True, exist_ok=True)


def load_fold_details(corpus: str, vp: str) -> pd.DataFrame | None:
    path = RESULTS_DIR / corpus / vp / "classification" / "fold_details.csv"
    if path.exists():
        return pd.read_csv(path)
    return None


def best_nonbaseline_scores(
    fold_df: pd.DataFrame, feature_config: str
) -> tuple[list[float], str] | None:
    subset = fold_df[
        (fold_df["feature_config"] == feature_config)
        & ~fold_df["classifier"].isin(["majority", "stratified"])
    ]
    if subset.empty:
        return None
    means = subset.groupby("classifier")["f1_macro"].mean()
    best_clf = means.idxmax()
    scores = subset[subset["classifier"] == best_clf]["f1_macro"].tolist()
    return scores, best_clf


def fixed_model_scores(
    fold_df: pd.DataFrame, feature_config: str, clf: str
) -> tuple[list[float], str] | None:
    """Fold scores for one (feature_config, classifier) cell under the paper's fixed model."""
    subset = fold_df[
        (fold_df["feature_config"] == feature_config) & (fold_df["classifier"] == clf)
    ]
    if subset.empty:
        return None
    return subset["f1_macro"].tolist(), clf


def run_wp1a() -> pd.DataFrame:
    print("=" * 60)
    print("WP1a: Global → Combined significance tests")
    print("=" * 60)

    rows = []
    for corpus in CORPORA:
        for vp in VP_CONFIGS:
            fold_df = load_fold_details(corpus, vp)
            if fold_df is None:
                print(f"  SKIP {corpus}/{vp}: no fold_details.csv")
                continue

            clf = PAPER_MODEL[corpus]
            global_result = fixed_model_scores(fold_df, "global", clf)
            combined_result = fixed_model_scores(fold_df, "combined", clf)

            if global_result is None or combined_result is None:
                print(f"  SKIP {corpus}/{vp}: missing global or combined config")
                continue

            global_scores, global_clf = global_result
            combined_scores, combined_clf = combined_result

            # Primary inference: Nadeau-Bengio corrected resampled t-test (accounts for the
            # variance inflation from overlapping training folds in repeated CV). Wilcoxon is
            # kept only as a secondary descriptor. This matches the manuscript's protocol and
            # `results/stats_corrected/ablation_corrected.csv`.
            k = N_SPLITS.get(corpus, 10)
            t_stat, t_p = corrected_resampled_ttest(
                combined_scores, global_scores, n_train=k - 1, n_test=1
            )
            try:
                w_stat, w_p = wilcoxon(combined_scores, global_scores, alternative="two-sided")
            except ValueError:
                w_stat, w_p = np.nan, np.nan

            d = cohens_d(combined_scores, global_scores)

            global_mean = float(np.mean(global_scores))
            combined_mean = float(np.mean(combined_scores))
            delta = combined_mean - global_mean

            rows.append({
                "corpus": corpus,
                "vp_config": vp,
                "global_clf": global_clf,
                "combined_clf": combined_clf,
                "global_mean": round(global_mean, 4),
                "combined_mean": round(combined_mean, 4),
                "delta": round(delta, 4),
                "delta_pct": round(delta / global_mean * 100, 1) if global_mean > 0 else 0,
                "corrected_t_stat": round(t_stat, 3),
                "corrected_t_p": t_p,
                "wilcoxon_stat": round(w_stat, 2) if not np.isnan(w_stat) else np.nan,
                "wilcoxon_p": w_p,
                "cohens_d": round(d, 3),
            })

            sig = "***" if t_p < 0.001 else "**" if t_p < 0.01 else "*" if t_p < 0.05 else "ns"
            print(
                f"  {corpus}/{vp}: global={global_mean:.3f} → combined={combined_mean:.3f} "
                f"(Δ={delta:+.3f}, corrected-t p={t_p:.4f}, d={d:.2f}) {sig}"
            )

    df = pd.DataFrame(rows)

    # Bonferroni per corpus (7 VP tests each) on BOTH p-values; significance uses the
    # corrected-t (the manuscript's primary statistic).
    for corpus in CORPORA:
        mask = df["corpus"] == corpus
        n_tests = int(mask.sum())
        if n_tests > 0:
            df.loc[mask, "corrected_t_bonferroni_p"] = (
                df.loc[mask, "corrected_t_p"] * n_tests
            ).clip(upper=1.0)
            df.loc[mask, "wilcoxon_bonferroni_p"] = (
                df.loc[mask, "wilcoxon_p"] * n_tests
            ).clip(upper=1.0)
            df.loc[mask, "significant_bonferroni"] = (
                df.loc[mask, "corrected_t_bonferroni_p"] < 0.05
            )

    return df


def _interpret_correlation(rho: float, p: float, n: int, ci_excludes_zero: bool) -> str:
    if n <= 7 and p >= 0.05:
        return f"underpowered (n={n}); suggestive only"
    if p < 0.05 and ci_excludes_zero:
        direction = "positive" if rho > 0 else "negative"
        return f"significant {direction} correlation"
    return "not significant"


def run_wp1b(significance_df: pd.DataFrame) -> pd.DataFrame:
    print("\n" + "=" * 60)
    print("WP1b: VP ranking correlations across corpora")
    print("=" * 60)

    corpus_rankings: dict[str, dict[str, int]] = {}
    for corpus in CORPORA:
        subset = significance_df[significance_df["corpus"] == corpus].copy()
        if subset.empty:
            continue
        subset = subset.sort_values("combined_mean", ascending=False)
        subset["rank"] = range(1, len(subset) + 1)
        corpus_rankings[corpus] = dict(zip(subset["vp_config"], subset["rank"]))

    rows = []
    corpus_list = list(corpus_rankings.keys())
    for i, c1 in enumerate(corpus_list):
        for c2 in corpus_list[i + 1:]:
            common_vps = sorted(set(corpus_rankings[c1]) & set(corpus_rankings[c2]))
            ranks_1 = [corpus_rankings[c1][vp] for vp in common_vps]
            ranks_2 = [corpus_rankings[c2][vp] for vp in common_vps]
            rho, p = spearmanr(ranks_1, ranks_2)

            rng = np.random.RandomState(42)
            n_boot = 10_000
            boot_rhos: list[float] = []
            f1_a: list[float] = []
            f1_b: list[float] = []
            for vp in common_vps:
                s1 = significance_df[
                    (significance_df["corpus"] == c1)
                    & (significance_df["vp_config"] == vp)
                ]["combined_mean"].iloc[0]
                s2 = significance_df[
                    (significance_df["corpus"] == c2)
                    & (significance_df["vp_config"] == vp)
                ]["combined_mean"].iloc[0]
                f1_a.append(s1)
                f1_b.append(s2)

            arr1 = np.array(f1_a)
            arr2 = np.array(f1_b)
            for _ in range(n_boot):
                idx = rng.choice(len(common_vps), len(common_vps), replace=True)
                if len(set(idx)) < 3:
                    continue
                r, _ = spearmanr(arr1[idx], arr2[idx])
                if not np.isnan(r):
                    boot_rhos.append(r)

            ci_lower = float(np.percentile(boot_rhos, 2.5)) if boot_rhos else float("nan")
            ci_upper = float(np.percentile(boot_rhos, 97.5)) if boot_rhos else float("nan")
            ci_excludes_zero = ci_lower > 0 or ci_upper < 0
            interpretation = _interpret_correlation(rho, p, len(common_vps), ci_excludes_zero)

            rows.append({
                "corpus_a": c1,
                "corpus_b": c2,
                "n_vp_configs": len(common_vps),
                "spearman_rho": round(rho, 3),
                "p_value": p,
                "boot_ci_lower": round(ci_lower, 3),
                "boot_ci_upper": round(ci_upper, 3),
                "ci_excludes_zero": ci_excludes_zero,
                "interpretation": interpretation,
            })

            print(
                f"  {c1} ↔ {c2}: ρ={rho:.3f} (p={p:.4f}), "
                f"95% CI [{ci_lower:.3f}, {ci_upper:.3f}] — {interpretation}"
            )

    return pd.DataFrame(rows)


def run_wp1c(significance_df: pd.DataFrame) -> pd.DataFrame:
    print("\n" + "=" * 60)
    print("WP1c: Variance comparison (Levene's test)")
    print("=" * 60)

    corpus_sigmas: dict[str, float] = {}
    corpus_f1_vecs: dict[str, np.ndarray] = {}
    for corpus in CORPORA:
        subset = significance_df[significance_df["corpus"] == corpus]
        f1_values = subset["combined_mean"].values
        sigma = float(np.std(f1_values, ddof=1))
        corpus_sigmas[corpus] = sigma
        corpus_f1_vecs[corpus] = f1_values
        print(f"  {corpus}: σ(combined F1) = {sigma:.4f}")

    rows = []
    corpus_list = list(corpus_f1_vecs.keys())
    for i, c1 in enumerate(corpus_list):
        for c2 in corpus_list[i + 1:]:
            stat, p = levene(corpus_f1_vecs[c1], corpus_f1_vecs[c2])
            rows.append({
                "corpus_a": c1,
                "corpus_b": c2,
                "sigma_a": round(corpus_sigmas[c1], 4),
                "sigma_b": round(corpus_sigmas[c2], 4),
                "sigma_ratio": round(
                    corpus_sigmas[c1] / corpus_sigmas[c2]
                    if corpus_sigmas[c2] > 0
                    else np.inf,
                    3,
                ),
                "levene_stat": round(float(stat), 3),
                "levene_p": float(p),
                "significant": float(p) < 0.05,
            })
            sig = "*" if p < 0.05 else "ns"
            print(
                f"  {c1} vs {c2}: σ={corpus_sigmas[c1]:.4f} vs {corpus_sigmas[c2]:.4f}, "
                f"Levene p={p:.4f} {sig}"
            )

    return pd.DataFrame(rows)


def main() -> None:
    print("Ablation Statistical Analysis")
    print("=" * 60)

    significance_df = run_wp1a()
    significance_df.to_csv(OUT_DIR / "ablation_significance.csv", index=False)
    print(f"\nSaved: {OUT_DIR / 'ablation_significance.csv'}")

    correlations_df = run_wp1b(significance_df)
    correlations_df.to_csv(OUT_DIR / "rank_correlations_ablation.csv", index=False)
    print(f"Saved: {OUT_DIR / 'rank_correlations_ablation.csv'}")

    variance_df = run_wp1c(significance_df)
    variance_df.to_csv(OUT_DIR / "variance_comparison.csv", index=False)
    print(f"Saved: {OUT_DIR / 'variance_comparison.csv'}")


if __name__ == "__main__":
    main()
