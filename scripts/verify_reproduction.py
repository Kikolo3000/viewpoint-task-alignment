#!/usr/bin/env python3
"""Compare regenerated CSVs against the reference set in results_reference/.

For each tracked CSV, numeric columns are compared within a tolerance;
non-numeric columns must match exactly. Exits non-zero on any mismatch.

Usage:
    uv run python scripts/verify_reproduction.py
"""
from __future__ import annotations

import logging
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parent.parent
RESULTS = REPO_ROOT / "results"
REFERENCE = REPO_ROOT / "results_reference"

logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
logger = logging.getLogger(__name__)

TOLERANCE = 1e-3

# Files under results_reference/ that we expect 01-07 to regenerate in results/.
TRACKED = [
    "viewpoint_comparison/ablation_significance.csv",
    "viewpoint_comparison/rank_correlations_ablation.csv",
    "viewpoint_comparison/variance_comparison.csv",
    "viewpoint_comparison/per_class_improvement_symbtr.csv",
    "viewpoint_comparison/per_class_improvement_the_session.csv",
    "viewpoint_comparison/per_class_improvement_essen.csv",
    "viewpoint_comparison/importance_shift_symbtr.csv",
    "viewpoint_comparison/importance_shift_the_session.csv",
    "viewpoint_comparison/importance_shift_essen.csv",
    "dance9/dance9_comparison/summary.csv",
]
# Note: classifier_robustness.csv and essen_diagnostic/comparison.csv are
# regenerated by 05 and 07 respectively, but no reference copy is tracked here
# because they depend on stochastic fold ordering across many classifiers and
# the original CSVs pre-date this release. Fig 8 and Fig 9 are validated by
# visual comparison with results_reference/figures/ instead.


def _compare_frames(ref: pd.DataFrame, cur: pd.DataFrame, rel: str) -> list[str]:
    errors: list[str] = []
    if ref.shape != cur.shape:
        errors.append(f"{rel}: shape mismatch (ref {ref.shape}, cur {cur.shape})")
        return errors
    if list(ref.columns) != list(cur.columns):
        errors.append(f"{rel}: column mismatch (ref {list(ref.columns)}, cur {list(cur.columns)})")
        return errors

    for col in ref.columns:
        ref_col = ref[col]
        cur_col = cur[col]
        is_numeric = (
            pd.api.types.is_numeric_dtype(ref_col)
            and pd.api.types.is_numeric_dtype(cur_col)
            and not pd.api.types.is_bool_dtype(ref_col)
            and not pd.api.types.is_bool_dtype(cur_col)
        )
        if is_numeric:
            diff = np.abs(ref_col.fillna(0).to_numpy(dtype=float)
                          - cur_col.fillna(0).to_numpy(dtype=float))
            nan_mismatch = ref_col.isna().to_numpy() ^ cur_col.isna().to_numpy()
            if nan_mismatch.any():
                errors.append(f"{rel}:{col}: NaN pattern mismatch in {int(nan_mismatch.sum())} rows")
            too_big = diff > TOLERANCE
            if too_big.any():
                max_diff = float(diff.max())
                errors.append(
                    f"{rel}:{col}: {int(too_big.sum())}/{len(diff)} values exceed tol "
                    f"(max diff {max_diff:.6f})"
                )
        else:
            if not ref_col.fillna("").astype(str).equals(cur_col.fillna("").astype(str)):
                mismatches = (ref_col.astype(str) != cur_col.astype(str)).sum()
                errors.append(f"{rel}:{col}: {int(mismatches)} non-numeric mismatches")
    return errors


def main() -> int:
    total_errors = 0
    total_ok = 0
    missing = 0

    for rel in TRACKED:
        ref_path = REFERENCE / rel
        cur_path = RESULTS / rel

        if not ref_path.exists():
            logger.warning("%s: no reference file at %s (skipping)", rel, ref_path)
            continue
        if not cur_path.exists():
            logger.error("%s: missing regenerated file at %s", rel, cur_path)
            missing += 1
            continue

        try:
            ref = pd.read_csv(ref_path)
        except pd.errors.EmptyDataError:
            ref = pd.DataFrame()
        try:
            cur = pd.read_csv(cur_path)
        except pd.errors.EmptyDataError:
            cur = pd.DataFrame()
        errors = _compare_frames(ref, cur, rel)
        if errors:
            for err in errors:
                logger.error("  %s", err)
            total_errors += len(errors)
        else:
            logger.info("OK  %s", rel)
            total_ok += 1

    logger.info("")
    logger.info("Summary: %d OK, %d mismatches, %d missing", total_ok, total_errors, missing)
    return 0 if (total_errors == 0 and missing == 0) else 1


if __name__ == "__main__":
    sys.exit(main())
